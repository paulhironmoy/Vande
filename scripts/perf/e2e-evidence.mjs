/**
 * Evidence records (release/player-experience/ceiling-rubric.md §8) from a Playwright JSON report of the accessibility
 * and robustness specs: one record per test, the rubric criteria taken from the "[A11Y1 …]" tag in its title.
 *
 *   node scripts/perf/e2e-evidence.mjs --report <results.json> --out <dir> --build <id> [--prefix E-A11Y] [--name E2E-all]
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { ROOT } from './serve.mjs';

const arg = (n, d) => (process.argv.includes(`--${n}`) ? process.argv[process.argv.indexOf(`--${n}`) + 1] : d);
const report = JSON.parse(readFileSync(resolve(ROOT, arg('report', 'test-results-perf/results.json')), 'utf8'));
const out = resolve(ROOT, arg('out', 'release/player-experience/shared/perf'));
const build = arg('build', 'unknown');
const prefix = arg('prefix', 'E-A11Y');
mkdirSync(out, { recursive: true });

const tests = [];
const walk = (suite, file) => {
  for (const s of suite.suites ?? []) walk(s, s.file ?? file);
  for (const spec of suite.specs ?? [])
    for (const t of spec.tests ?? []) {
      const r = t.results?.at(-1);
      // eslint-disable-next-line no-control-regex -- the ESC character is what introduces an ANSI colour code
      tests.push({ file: spec.file ?? file, title: spec.title, status: r?.status ?? 'skipped', ms: r?.duration ?? 0, error: (r?.error?.message ?? '').replace(/\u001b\[[0-9;]*m/g, '').split('\n').slice(0, 6).join(' / '), annotations: (t.annotations ?? []).map((a) => `${a.type}: ${a.description}`).join(' / '), start: r?.startTime ?? '' });
    }
};
for (const s of report.suites ?? []) walk(s, s.file);

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
let id = 1;
const rows = tests.map((t) => {
  const tag = t.title.match(/^\[([A-Z0-9 ]+)\]/);
  return {
    id: `${prefix}-${String(id++).padStart(3, '0')}`,
    criteria: tag ? tag[1] : '–',
    build,
    time: t.start,
    device: 'Apple M1 Pro, macOS 15, headless Chromium (Playwright practice project), WebGL on SwiftShader',
    settings: t.title.replace(/^\[[A-Z0-9 ]+\]\s*/, ''),
    method: `${t.file} (Practice test-hooks build, isolated: E2E_PRACTICE_PORT=4203 E2E_PRACTICE_DIST=dist-perf)`,
    expected: 'the test’s assertions (see the spec)',
    observed: t.status === 'passed' ? `passed in ${Math.round(t.ms / 1000)} s${t.annotations ? `; ${t.annotations.slice(0, 600)}` : ''}` : `${t.status}: ${t.error.slice(0, 900)}`,
    result: t.status === 'passed' ? 'Pass' : t.status === 'skipped' ? 'n/a' : 'Fail',
    path: relative(ROOT, resolve(ROOT, arg('report', 'test-results-perf/results.json'))),
  };
});
// One file per run of the specs on this build (rerunning replaces it; the raw report stays next to it).
const file = join(out, `EVIDENCE-${arg('name', 'E2E')}.md`);
const head = ['| ID | Criteria | Build id | Time (UTC) | Device and browser | Settings | Method | Expected | Observed | Result | Evidence path |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |'];
writeFileSync(
  file,
  `# Accessibility and robustness evidence, build ${build}\n\nGenerated by scripts/perf/e2e-evidence.mjs on ${new Date().toISOString()}. Builder evidence: per rubric R3 it counts once an evaluator reruns it (\`scripts/perf/run-a11y.sh\`).\n\n${head.join('\n')}\n` +
    rows.map((r) => `| ${r.id} | ${r.criteria} | ${r.build} | ${r.time} | ${esc(r.device)} | ${esc(r.settings)} | ${esc(r.method)} | ${esc(r.expected)} | ${esc(r.observed)} | ${r.result} | ${esc(r.path)} |`).join('\n') +
    '\n',
);
console.log(`${rows.length} records (${rows.filter((r) => r.result === 'Fail').length} fail) → ${relative(ROOT, file)}`);
for (const r of rows) console.log(`  ${r.id} ${r.result.padEnd(4)} [${r.criteria}] ${r.settings}`);
