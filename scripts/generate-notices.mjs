#!/usr/bin/env node
/**
 * Third-party notices for everything VANDE Cricket ships, written to public/third-party-notices.txt (shipped in the web
 * build and the APK, shown in Settings → Open-source licences):
 *   - production npm packages (`npm query .prod`) with their own licence texts;
 *   - with --android, the Android libraries in the release runtime classpath (Gradle), their licences from the POMs in
 *     the Gradle cache, and the full Apache License 2.0 text they require.
 *
 *   node scripts/generate-notices.mjs [--android]
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';

const ROOT = resolve(new URL('..', import.meta.url).pathname);
const withAndroid = process.argv.includes('--android');
const out = [];
const line = (s = '') => out.push(s);
const rule = () => line('='.repeat(78));

function licenceText(dir) {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying|ofl)(\.(md|txt))?$/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : null;
}

// ---- npm --------------------------------------------------------------------------------------------------------
const prod = JSON.parse(execFileSync('npm', ['query', '.prod'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64 << 20 }))
  .filter((p) => p.path !== ROOT)
  .sort((a, b) => a.name.localeCompare(b.name));

line('VANDE Cricket: third-party notices');
line('Generated by scripts/generate-notices.mjs. VANDE Cricket itself is proprietary; the components below keep their own licences.');
line('Fonts: Manrope and Noto Sans (SIL Open Font License 1.1). All artwork, sounds, players and stadiums are generated by the app itself.');
line();
rule();
line(`Web and app components (${prod.length} npm packages)`);
rule();
const missing = [];
for (const p of prod) {
  line();
  line(`${p.name} ${p.version}  —  ${p.license ?? 'UNKNOWN'}${p.homepage ? `  —  ${p.homepage}` : ''}`);
  line('-'.repeat(78));
  const text = existsSync(p.path) ? licenceText(p.path) : null;
  if (text) line(text);
  else {
    line(`(No licence file in the package; licence: ${p.license ?? 'unknown'}.)`);
    missing.push(p.name);
  }
}

// ---- Android ------------------------------------------------------------------------------------------------------
if (withAndroid) {
  const env = { ...process.env, JAVA_HOME: process.env.JAVA_HOME || '/Applications/Android Studio.app/Contents/jbr/Contents/Home' };
  const tree = execFileSync('./gradlew', ['-q', ':app:dependencies', '--configuration', 'releaseRuntimeClasspath'], { cwd: join(ROOT, 'android'), env, encoding: 'utf8', maxBuffer: 64 << 20 });
  const libs = new Map();
  for (const raw of tree.split('\n')) {
    const m = /[+\\]--- ([\w.-]+):([\w.-]+):([\w.+-]+)(?: -> ([\w.+-]+))?/.exec(raw);
    if (m) libs.set(`${m[1]}:${m[2]}`, m[4] ?? m[3]);
  }
  const cache = join(homedir(), '.gradle/caches/modules-2/files-2.1');
  const pomLicence = (group, artifact, version) => {
    const dir = join(cache, group, artifact, version);
    if (!existsSync(dir)) return null;
    for (const hash of readdirSync(dir)) {
      const pom = join(dir, hash, `${artifact}-${version}.pom`);
      if (!existsSync(pom)) continue;
      const xml = readFileSync(pom, 'utf8');
      const names = [...xml.matchAll(/<license>\s*<name>([^<]+)<\/name>(?:\s*<url>([^<]+)<\/url>)?/g)].map((x) => `${x[1].trim()}${x[2] ? ` (${x[2].trim()})` : ''}`);
      return names.length ? names.join('; ') : null;
    }
    return null;
  };
  line();
  rule();
  line(`Android libraries (${libs.size}, release runtime classpath)`);
  rule();
  const sorted = [...libs.entries()].sort((a, b) => a[0].localeCompare(b[0]));
  for (const [ga, version] of sorted) {
    const [group, artifact] = ga.split(':');
    const lic = pomLicence(group, artifact, version) ?? (/^(androidx|com\.google\.(firebase|android\.datatransport))\b|^org\.jetbrains/.test(group) ? 'The Apache Software License, Version 2.0' : 'see the library\'s published terms');
    line(`${ga}:${version}  —  ${lic}`);
  }
  line('Capacitor Android runtime and plugins (@capacitor/*)  —  MIT (texts above)');
  const apache = ['typescript/LICENSE.txt', 'tslib/LICENSE.txt'].map((f) => join(ROOT, 'node_modules', f)).find((f) => existsSync(f) && /Apache License\s+Version 2\.0, January 2004/.test(readFileSync(f, 'utf8')));
  line();
  rule();
  line('Apache License, Version 2.0 (full text, for the Android libraries above)');
  rule();
  if (apache) line(readFileSync(apache, 'utf8').slice(readFileSync(apache, 'utf8').indexOf('Apache License')).trim());
  else line('The full text is at https://www.apache.org/licenses/LICENSE-2.0.txt');
}

writeFileSync(join(ROOT, 'public/third-party-notices.txt'), `${out.join('\n')}\n`);
console.log(`wrote public/third-party-notices.txt (${prod.length} npm packages${withAndroid ? ' + Android libraries' : ''})${missing.length ? `; no licence file: ${missing.join(', ')}` : ''}`);
