#!/usr/bin/env node
/**
 * The Unity side of the face-and-life Director's parameters (contract director/3, UNITY-E1).
 *
 * `src/render3d/core/motion/director/params.json` is the single source of every tunable number of the Director. Unity
 * cannot read outside Assets/, so this script keeps two derived files in the Unity project:
 *
 *   1. a byte-identical copy of params.json (a test fixture the EditMode tests hash), and
 *   2. DirectorParams.Generated.cs: every number of the file as a C# constant, so the C# port has no hand-typed tunable
 *      number and reads no file at run time. The generated class also carries the FNV-1a 32 of the file's bytes, which
 *      the Unity EditMode test DirectorVendoredTests compares with the copy, and the length of the minified JSON, which
 *      golden.json records as `paramsBytes`.
 *
 *   node scripts/director-unity-params.mjs            write both files
 *   node scripts/director-unity-params.mjs --check    exit 1 when either is stale (what the web test does in process)
 *
 * The web test tests/unit/render3d/director/unityVendored.test.ts fails when params.json changed and this script was not
 * run, so a parameter can never change on one side only. A change to params.json is a deliberate new freeze of the
 * contract (golden.test.ts) and then needs a new golden.json; this script does not touch that file.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const UNITY = 'unity/VandePractice/Assets/VandePractice';

/** Repository-relative paths. */
export const WEB_PARAMS = 'src/render3d/core/motion/director/params.json';
export const UNITY_PARAMS_COPY = `${UNITY}/Tests/EditMode/Director/Fixtures/params.json`;
export const UNITY_GENERATED = `${UNITY}/Runtime/Presentation/Production/Director/DirectorParams.Generated.cs`;

/** FNV-1a 32 over bytes (the C# EditMode test computes the same over the Unity copy's bytes). */
export function fnv1a32Bytes(bytes) {
  let h = 0x811c9dc5;
  for (let i = 0; i < bytes.length; i++) {
    h ^= bytes[i];
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}

const pascal = (key) =>
  key
    .split('_')
    .filter((p) => p.length > 0)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join('');

const isNumberArray = (v) => Array.isArray(v) && v.length > 0 && v.every((x) => typeof x === 'number' && Number.isFinite(x));

/** A JavaScript number as a C# double literal that parses to the same double (String(n) is the shortest round-trip form). */
function literal(n) {
  const s = String(n);
  if (/^-?\d+$/.test(s)) return `${s}.0`;
  return s;
}

function emit(obj, indent, lines) {
  const pad = '    '.repeat(indent);
  for (const [key, value] of Object.entries(obj)) {
    if (key === '_') {
      lines.push(`${pad}/// <summary>The parameter file's own note on its units.</summary>`);
      lines.push(`${pad}public const string Note = ${JSON.stringify(String(value))};`);
      continue;
    }
    const name = pascal(key);
    if (typeof value === 'number') {
      lines.push(`${pad}public const double ${name} = ${literal(value)};`);
    } else if (isNumberArray(value)) {
      lines.push(`${pad}public static readonly double[] ${name} = { ${value.map(literal).join(', ')} };`);
    } else if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      lines.push(`${pad}public static class ${name}`);
      lines.push(`${pad}{`);
      emit(value, indent + 1, lines);
      if (key === 'table') {
        // react.table is looked up by the outcome's category (a string), so it gets a lookup without allocation.
        lines.push(`${pad}    /// <summary>The row of an outcome category, or null for a category the table does not have.</summary>`);
        lines.push(`${pad}    public static double[] Row(string category)`);
        lines.push(`${pad}    {`);
        lines.push(`${pad}        switch (category)`);
        lines.push(`${pad}        {`);
        for (const k of Object.keys(value)) lines.push(`${pad}            case ${JSON.stringify(k)}: return ${pascal(k)};`);
        lines.push(`${pad}            default: return null;`);
        lines.push(`${pad}        }`);
        lines.push(`${pad}    }`);
      }
      lines.push(`${pad}}`);
    } else {
      throw new Error(`params.json: ${key} is neither a number, an array of numbers nor an object`);
    }
  }
}

/** The C# source for a params.json text (deterministic: same text in, same text out, LF line ends). */
export function generateDirectorParams(jsonText) {
  const params = JSON.parse(jsonText);
  const bytes = Buffer.from(jsonText, 'utf8');
  const lines = [];
  lines.push('// <auto-generated>');
  lines.push('// Generated from src/render3d/core/motion/director/params.json by scripts/director-unity-params.mjs. Do not edit.');
  lines.push('// Change params.json (a deliberate new freeze of the Director contract), run `node scripts/director-unity-params.mjs`,');
  lines.push('// and re-record the golden fixture. The web test unityVendored.test.ts and the Unity test DirectorVendoredTests fail');
  lines.push('// when this file, the Unity copy of params.json and the web file disagree.');
  lines.push('// The arrays below are shared and must be treated as read-only (the Director never writes to them).');
  lines.push('// </auto-generated>');
  lines.push('');
  lines.push('namespace Vande.Practice.Presentation.Production.Director');
  lines.push('{');
  lines.push('    /// <summary>Every tunable number of the Director (params.json), one constant per number; units follow each name\'s suffix (Ms, S, Deg, DegS, Hz, Mm, Cycles, P, X).</summary>');
  lines.push('    public static class DirectorParams');
  lines.push('    {');
  lines.push(`        /// <summary>FNV-1a 32 of the bytes of params.json this file was generated from.</summary>`);
  lines.push(`        public const uint SourceFnv1a32 = 0x${fnv1a32Bytes(bytes).toString(16).padStart(8, '0')}u;`);
  lines.push('        /// <summary>The length in bytes of params.json this file was generated from.</summary>');
  lines.push(`        public const int SourceBytes = ${bytes.length};`);
  lines.push('        /// <summary>The length of the minified JSON (golden.json records it as paramsBytes).</summary>');
  lines.push(`        public const int MinifiedChars = ${JSON.stringify(params).length};`);
  lines.push('');
  emit(params, 2, lines);
  lines.push('    }');
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/** What the script would write, from the web file as it is now. */
export function expectedFiles(root = ROOT) {
  const webText = readFileSync(resolve(root, WEB_PARAMS), 'utf8');
  return { params: webText, generated: generateDirectorParams(webText) };
}

/** The names of the derived files that are missing or stale. */
export function staleFiles(root = ROOT) {
  const want = expectedFiles(root);
  const stale = [];
  const copy = resolve(root, UNITY_PARAMS_COPY);
  if (!existsSync(copy) || readFileSync(copy, 'utf8') !== want.params) stale.push(UNITY_PARAMS_COPY);
  const gen = resolve(root, UNITY_GENERATED);
  if (!existsSync(gen) || readFileSync(gen, 'utf8') !== want.generated) stale.push(UNITY_GENERATED);
  return stale;
}

function main() {
  const check = process.argv.includes('--check');
  const stale = staleFiles();
  if (check) {
    if (stale.length > 0) {
      console.error(`stale: ${stale.join(', ')}\nrun: node scripts/director-unity-params.mjs`);
      process.exit(1);
    }
    console.log('Unity Director parameters are current');
    return;
  }
  const want = expectedFiles();
  mkdirSync(dirname(resolve(ROOT, UNITY_PARAMS_COPY)), { recursive: true });
  mkdirSync(dirname(resolve(ROOT, UNITY_GENERATED)), { recursive: true });
  copyFileSync(resolve(ROOT, WEB_PARAMS), resolve(ROOT, UNITY_PARAMS_COPY));
  writeFileSync(resolve(ROOT, UNITY_GENERATED), want.generated);
  console.log(stale.length > 0 ? `wrote ${stale.join(', ')}` : 'already current');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
