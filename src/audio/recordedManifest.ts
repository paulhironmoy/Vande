/**
 * The recorded-sound manifest: wedge §7.2's fourteen kinds in priority order, the runtime sound each maps to, and the
 * takes that exist for it. Every take is a file in public/audio/cricket/ (and, byte for byte, in Unity's
 * Resources/Audio/Cricket/), registered in release/product-sequence/stage-1-practice/wedge/sound/REGISTER.md (the
 * `register` id). The applause takes come from that folder's tools/process_takes.py (its processed.json holds the
 * measurements); the contact takes are written by scripts/audio/ (CONTACT_TAKES below).
 *
 * Contact takes are either licensed or owner-made recordings, or **placeholders**: original synthesised takes rendered
 * offline by scripts/audio/placeholders.mjs (impact and modal synthesis, no samples), levelled to the live synthesised
 * voice they stand in for. A placeholder kind is marked `placeholder: true` and says so in `honest`; it is never
 * described as a recording, and scripts/audio/ingest-recordings.mjs --apply swaps a sound's placeholders for
 * recordings in one step.
 *
 * The synthesised voices stay the fallback for every kind, and for every take that is missing or fails to load
 * (src/audio/recorded.ts). `honest` says what the takes are, and are not (docs/UNITY_ASSET_AUDIO_READINESS.md §1).
 */
import type { FxId } from './bank';
import type { CrowdReaction } from './emotionCore';

/** A sound the runtime plays: an effect id, or a crowd reaction. */
export type RecordedKey = FxId | `crowd:${CrowdReaction}`;

export interface RecordedTake {
  /** Also the file's base name. */
  id: string;
  /** Under public/audio/cricket/. */
  file: string;
  bytes: number;
  sha256: string;
  /** REGISTER.md row. */
  register: string;
  /** Integrated loudness (ITU-R BS.1770) of the decoded file, where at least one 400 ms block exists. */
  lufs: number | null;
  peakDbfs: number;
  durationMs: number;
}

export interface RecordedKind {
  key: RecordedKey;
  /** Wedge §7.2 inventory item, 1 (the middled tock) … 14 (fielder calls). */
  inventory: number;
  label: string;
  /** What the takes are, and what they are not. */
  honest: string;
  /** 'onset': the transient lands on the event's time (COH6). 'start': the buffer starts on it (crowd reactions). */
  align: 'onset' | 'start';
  /** Material kept before the onset (ms). */
  prerollMs: number;
  /** Decoded takes above this sample rate are resampled down once, to save memory (crowd layers). */
  maxRate?: number;
  /** The takes are original synthesised placeholders (scripts/audio/placeholders.mjs), not recordings. */
  placeholder?: true;
  takes: readonly RecordedTake[];
}

/** One contact sound's takes: placeholders, or recordings (`honest` says which, and what they are not). */
export interface ContactTakeSet {
  placeholder: boolean;
  honest: string;
  takes: readonly RecordedTake[];
}

